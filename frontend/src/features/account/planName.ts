import { useTranslation } from 'react-i18next'
import { useLocalized } from '../../lib/useLocalized'
import type { SavedPlanSummary } from '../../types/api'
import { useServices } from '../services/api'

type Nameable = Pick<SavedPlanSummary, 'title' | 'target_service_ids'> & { goals?: string[] }

/** Separator used by names that older versions generated and stored as text. */
const LEGACY_SEPARATOR = /,\s*|،\s*/
const PREFIX_SEPARATOR = ' — '

/**
 * Plan display names, built at the presentation layer in the current language.
 *
 * - A name the citizen typed is shown exactly as typed (never translated or overwritten).
 * - No name: the plan's intended services (never planner-added prerequisites), or, for a
 *   situation plan, its goals.
 * - Older plans stored a generated name as text ("A, B", "Prefix — A", or goal labels) in the
 *   language of that moment. Those are recognised (every part is a catalogue service or goal name,
 *   in English or Hindi) and rebuilt from the plan's CURRENT services, so they follow the language
 *   and never go stale after services are edited. The stored data is not changed.
 */
export function usePlanName() {
  const { t, i18n } = useTranslation()
  const pick = useLocalized()
  const services = useServices()
  const svcByName = new Map<string, string>()
  for (const s of services.data ?? []) {
    svcByName.set(s.name.trim().toLocaleLowerCase(), s.id)
    if (s.name_hi) svcByName.set(s.name_hi.trim().toLocaleLowerCase(), s.id)
  }
  const goalByLabel = new Map<string, string>()
  for (const lng of ['en', 'hi']) {
    const goals = (i18n.getResourceBundle(lng, 'translation') as { goals?: Record<string, string> } | undefined)?.goals ?? {}
    for (const [id, label] of Object.entries(goals)) goalByLabel.set(label.trim().toLocaleLowerCase(), id)
  }
  const sep = t('common.listSeparator')
  const service = (id: string) => {
    const s = services.data?.find((x) => x.id === id)
    return s ? pick(s.name, s.name_hi) : id
  }
  const goal = (id: string) => t(`goals.${id}`, { defaultValue: id })
  const fromPlan = (p: Nameable) =>
    p.goals?.length ? p.goals.map(goal).join(sep) : p.target_service_ids.map(service).join(sep) || t('account.untitledPlan')
  const parts = (title: string) => title.split(LEGACY_SEPARATOR).map((x) => x.trim().toLocaleLowerCase()).filter(Boolean)

  /** True when a stored title was generated by the app (not typed by the citizen). */
  const isGenerated = (title: string | null | undefined): boolean => {
    if (!title) return true
    const ps = parts(title)
    if (ps.length && ps.every((x) => svcByName.has(x))) return true
    if (ps.length && ps.every((x) => goalByLabel.has(x))) return true
    return false
  }

  /** Display name for a plan (or for a title alone, e.g. in history, when the plan is gone). */
  const name = (p: Nameable | { title: string | null | undefined; target_service_ids?: string[]; goals?: string[] }): string => {
    const title = p.title?.trim() ?? ''
    const targets = p.target_service_ids ?? []
    if (!title) return targets.length || p.goals?.length ? fromPlan({ title: null, target_service_ids: targets, goals: p.goals }) : t('account.untitledPlan')
    const ps = parts(title)
    if (ps.length && ps.every((x) => svcByName.has(x))) {
      // Generated from services: show the plan's current services (or the named ones if unknown).
      return (targets.length ? targets : ps.map((x) => svcByName.get(x)!)).map(service).join(sep)
    }
    if (ps.length && ps.every((x) => goalByLabel.has(x))) return ps.map((x) => goal(goalByLabel.get(x)!)).join(sep)
    const i = title.lastIndexOf(PREFIX_SEPARATOR)
    if (i > 0) {
      const suffix = title.slice(i + PREFIX_SEPARATOR.length).trim().toLocaleLowerCase()
      const id = svcByName.get(suffix)
      if (id) return `${title.slice(0, i)}${PREFIX_SEPARATOR}${service(targets.length === 1 ? targets[0] : id)}`
    }
    return title // typed by the citizen
  }
  return { name, isGenerated }
}
